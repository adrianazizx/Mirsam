//! Turns the measurements into `results.md` / `results.json` in the output directory.

use std::fmt::Write as _;
use std::path::Path;

use crate::{INPUTS, Output};

pub fn codepoints(s: &str) -> String {
    if s.is_empty() {
        return "(nothing)".into();
    }
    s.chars().map(|c| format!("U+{:04X}", c as u32)).collect::<Vec<_>>().join(" ")
}

pub struct Comparison {
    pub exact: bool,
    /// Why it differs, when it does.
    pub class: &'static str,
    /// Levenshtein distance in characters.
    pub distance: usize,
    pub got: String,
}

fn is_bidi_control(c: char) -> bool {
    matches!(c, '\u{200E}' | '\u{200F}' | '\u{061C}' | '\u{202A}'..='\u{202E}' | '\u{2066}'..='\u{2069}')
}

pub fn compare(expected: &str, raw: &str) -> Comparison {
    // Extractors end a page's text with a line terminator; that is not a difference.
    let got = raw.trim_end_matches(['\r', '\n']).to_string();
    let no_controls = |s: &str| s.chars().filter(|c| !is_bidi_control(*c)).collect::<String>();
    let no_space =
        |s: &str| s.chars().filter(|c| !c.is_whitespace() && !is_bidi_control(*c)).collect::<String>();
    let sorted = |s: &str| {
        let mut v: Vec<char> = no_space(s).chars().collect();
        v.sort_unstable();
        v
    };
    let class = if got == expected {
        "exact"
    } else if got.is_empty() {
        "no text extracted"
    } else if no_controls(&got) == expected {
        "only bidi control characters added"
    } else if no_space(&got) == no_space(expected) {
        "only whitespace differs"
    } else if sorted(&got) == sorted(expected) {
        "same characters, different order"
    } else {
        "characters differ"
    };
    Comparison { exact: got == expected, class, distance: levenshtein(expected, &got), got }
}

fn levenshtein(a: &str, b: &str) -> usize {
    let (a, b): (Vec<char>, Vec<char>) = (a.chars().collect(), b.chars().collect());
    let mut row: Vec<usize> = (0..=b.len()).collect();
    for i in 1..=a.len() {
        let mut prev = row[0];
        row[0] = i;
        for j in 1..=b.len() {
            let cur = row[j];
            row[j] = if a[i - 1] == b[j - 1] { prev } else { 1 + prev.min(row[j]).min(row[j - 1]) };
            prev = cur;
        }
    }
    row[b.len()]
}

/// Makes invisible characters visible without touching ordinary text.
fn visible(s: &str) -> String {
    s.chars()
        .map(|c| {
            if is_bidi_control(c)
                || c.is_control()
                || c == '\u{FFFD}'
                || ('\u{E000}'..='\u{F8FF}').contains(&c)
            {
                format!("\\u{{{:04X}}}", c as u32)
            } else {
                c.to_string()
            }
        })
        .collect()
}

fn cell(expected: &str, texts: &[String], index: usize) -> String {
    match texts.get(index) {
        None => "n/a".into(),
        Some(raw) => {
            let c = compare(expected, raw);
            if c.exact { "yes".into() } else { format!("NO ({})", c.distance) }
        }
    }
}

/// Extraction of a PDF this spike did not write (Chrome's print of a fixture).
pub struct Reference {
    pub stem: String,
    pub pdfium: Vec<String>,
    pub pdfkit: Vec<String>,
}

pub fn write(
    out_dir: &Path,
    all: &[Output],
    references: &[Reference],
    insertions: &[crate::insert::Outcome],
) -> Result<(), Box<dyn std::error::Error>> {
    let (probes, outputs): (Vec<&Output>, Vec<&Output>) = all.iter().partition(|o| o.probe);
    let mut md = String::new();
    writeln!(md, "# pdfium-edit spike: measured results\n")?;
    writeln!(
        md,
        "Generated by `cargo run -p spike-pdfium-edit`. Do not edit; see ../../pdfium-edit/README.md.\n"
    )?;
    writeln!(md, "Extraction cells: `yes` = extracted page text equals the logical input string exactly")?;
    writeln!(
        md,
        "(after dropping the trailing line terminator); `NO (n)` = differs, n = edit distance in characters.\n"
    )?;

    writeln!(md, "## Files\n")?;
    writeln!(
        md,
        "| variant | font | qpdf --check | file bytes | font program bytes | original TTF | subset? | CIDToGIDMap | ToUnicode: used glyphs mapped / correct / used | text objects (4 pages) | show ops | marked spans | content bytes | pixels differing from b-src (worst page) |"
    )?;
    writeln!(md, "|---|---|---|---:|---:|---:|---|---|---|---:|---:|---:|---:|---:|")?;
    for o in &outputs {
        let program: usize = o.inspection.font_programs.iter().sum();
        let pages = &o.inspection.pages;
        writeln!(
            md,
            "| {} | {} | {} | {} | {} | {} | {} | {} | {} / {} / {} | {} | {} | {} | {} | {:.3}% |",
            o.spec_key,
            o.font_key,
            o.qpdf,
            o.inspection.file_size,
            program,
            o.font_file_size,
            if program * 2 < o.font_file_size { "yes" } else { "NO (whole font)" },
            o.inspection.cid_to_gid,
            o.tounicode_mapped,
            o.tounicode_correct,
            o.tounicode_used,
            pages.iter().map(|p| p.text_objects).sum::<usize>(),
            pages.iter().map(|p| p.show_ops).sum::<usize>(),
            pages.iter().map(|p| p.marked_spans).sum::<usize>(),
            pages.iter().map(|p| p.content_bytes).sum::<usize>(),
            o.render_diff.iter().cloned().fold(0.0, f64::max) * 100.0,
        )?;
    }

    writeln!(md, "\n## Text extraction round-trip\n")?;
    write!(md, "| variant | font |")?;
    for (key, _) in INPUTS {
        write!(md, " {key}: PDFium | {key}: PDFKit |")?;
    }
    writeln!(md)?;
    writeln!(md, "|---|---|{}", "---|---|".repeat(INPUTS.len()))?;
    for o in &outputs {
        write!(md, "| {} | {} |", o.spec_key, o.font_key)?;
        for (index, (_, text)) in INPUTS.iter().enumerate() {
            write!(md, " {} | {} |", cell(text, &o.pdfium_text, index), cell(text, &o.pdfkit_text, index))?;
        }
        writeln!(md)?;
    }

    writeln!(md, "\n## Variants\n")?;
    let mut seen = Vec::new();
    for o in &outputs {
        if !seen.contains(&o.spec_key) {
            seen.push(o.spec_key);
            writeln!(md, "- `{}`: {}", o.spec_key, o.what)?;
        }
    }

    writeln!(md, "\n## Route A API failures\n")?;
    let mut any = false;
    for o in &outputs {
        if let Some(stats) = &o.a_stats {
            for failure in &stats.failures {
                any = true;
                writeln!(md, "- {}: {failure}", o.stem)?;
            }
        }
    }
    if !any {
        writeln!(md, "None: every PDFium call returned success.")?;
    }

    writeln!(
        md,
        "\n## ToUnicode gaps (glyphs the shaper used whose ToUnicode entry is missing or not the source text)\n"
    )?;
    for o in outputs.iter().filter(|o| !o.tounicode_gaps.is_empty()) {
        writeln!(md, "### {} ({} of {} used glyphs)\n", o.stem, o.tounicode_gaps.len(), o.tounicode_used)?;
        for gap in o.tounicode_gaps.iter().take(15) {
            writeln!(md, "- {gap}")?;
        }
        if o.tounicode_gaps.len() > 15 {
            writeln!(md, "- ... and {} more", o.tounicode_gaps.len() - 15)?;
        }
        writeln!(md)?;
    }

    writeln!(md, "## Mismatches in full\n")?;
    for (index, (key, text)) in INPUTS.iter().enumerate() {
        writeln!(md, "### Input `{key}`\n\nexpected: `{text}`\n")?;
        for o in &outputs {
            for (name, texts) in [("PDFium", &o.pdfium_text), ("PDFKit", &o.pdfkit_text)] {
                let Some(raw) = texts.get(index) else { continue };
                let c = compare(text, raw);
                if !c.exact {
                    writeln!(
                        md,
                        "- {} / {name}: {} (distance {})  \n  got: `{}`",
                        o.stem,
                        c.class,
                        c.distance,
                        visible(&c.got)
                    )?;
                }
            }
        }
        writeln!(md)?;
    }
    writeln!(md, "## /ActualText probes\n")?;
    writeln!(md, "Same glyphs as `b-src`, but every /ActualText holds a marker instead of the real text.")?;
    writeln!(
        md,
        "An extractor that honours the span returns the marker; one that ignores it returns the ToUnicode text.\n"
    )?;
    for o in &probes {
        writeln!(md, "### {} ({})\n", o.stem, o.what)?;
        for (index, (key, _)) in INPUTS.iter().enumerate() {
            for (name, texts) in [("PDFium", &o.pdfium_text), ("PDFKit", &o.pdfkit_text)] {
                let got = texts.get(index).map(|t| t.trim_end_matches(['\r', '\n'])).unwrap_or("n/a");
                writeln!(md, "- {key} / {name}: `{}`", visible(got))?;
            }
        }
        writeln!(md)?;
    }
    writeln!(md, "## Inserting one line into the first page of an existing PDF\n")?;
    writeln!(
        md,
        "The vocalized line in Amiri, 14 pt, added near the bottom of page 1 of fixtures this spike did not write."
    )?;
    writeln!(
        md,
        "`kept` columns compare page 1 before and after: its decoded content stream bytes (still present verbatim),"
    )?;
    writeln!(
        md,
        "its pixels above the new line, and its extracted text (still a contiguous part of the new text)."
    )?;
    writeln!(md, "Times are wall-clock for load + insert + save in this debug build, one run each.\n")?;
    writeln!(
        md,
        "| source | route | result | bytes before -> after | ms | qpdf --check | text objects added | content streams on page 1 | content bytes kept | pixels changed above the line | pixels changed in the line's band | PDFium text kept | PDFKit text kept | output encrypted | PDFium opens source / output | object definitions in output | of which after a verbatim copy of the source |"
    )?;
    writeln!(md, "|---|---|---|---|---:|---|---:|---:|---|---:|---:|---|---|---|---|---:|---:|")?;
    let flag = |v: Option<bool>| v.map(|b| if b { "yes" } else { "NO" }).unwrap_or("n/a").to_string();
    for o in insertions {
        match &o.result {
            Ok(bytes) => writeln!(
                md,
                "| {} | {} | ok | {} -> {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} / {} | {} | {} |",
                o.case,
                o.route,
                o.source_bytes,
                bytes,
                o.millis,
                o.qpdf,
                o.objects,
                o.content_streams.map(|n| n.to_string()).unwrap_or_else(|| "n/a".into()),
                flag(o.content_kept),
                o.pixels_changed.map(|f| format!("{:.4}%", f * 100.0)).unwrap_or_else(|| "n/a".into()),
                o.band_pixels_changed.map(|n| n.to_string()).unwrap_or_else(|| "n/a".into()),
                o.pdfium_text_kept.map(|k| k.label()).unwrap_or("n/a"),
                o.pdfkit_text_kept.map(|k| k.label()).unwrap_or("n/a"),
                flag(o.output_encrypted),
                flag(o.pdfium_opens_source),
                flag(o.pdfium_opens_output),
                o.objects_written.map(|n| n.to_string()).unwrap_or_else(|| "n/a".into()),
                o.objects_after_source.map(|n| n.to_string()).unwrap_or_else(|| "n/a".into()),
            )?,
            Err(error) => writeln!(
                md,
                "| {} | {} | FAILED: {} | {} -> n/a | {} | n/a | | | | | | | | | | | |",
                o.case, o.route, error, o.source_bytes, o.millis
            )?,
        }
    }
    writeln!(md)?;
    for o in insertions {
        if let Some(excerpt) = &o.pdfium_excerpt {
            writeln!(
                md,
                "PDFium text of `{}.pdf`, page 1, characters 60 to 150: `{}`\n",
                o.stem,
                visible(excerpt)
            )?;
        }
    }
    if let Some(o) = insertions.iter().find(|o| o.password.is_some()) {
        writeln!(md, "`{}` was opened with its test password.\n", o.case)?;
    }

    writeln!(md, "## Reference: Chrome-printed fixtures through the same two extractors\n")?;
    writeln!(
        md,
        "Copies of `fixtures/out/chrome/*.pdf` (multi-paragraph pages written by Skia's PDF backend)."
    )?;
    writeln!(md, "Inputs `vocalized` and `mixed` appear verbatim in `ar-vocalized` and `mixed-inline`.\n")?;
    for r in references {
        for (name, texts) in [("PDFium", &r.pdfium), ("PDFKit", &r.pdfkit)] {
            writeln!(md, "### {} / {name}\n\n```text", r.stem)?;
            for page in texts {
                writeln!(md, "{}", visible(&page.replace("\r\n", "\n")).replace("\\u{000A}", "\n"))?;
            }
            writeln!(md, "```\n")?;
        }
    }
    std::fs::write(out_dir.join("results.md"), md)?;

    let json: Vec<serde_json::Value> = all
        .iter()
        .map(|o| {
            let extraction: Vec<serde_json::Value> = INPUTS
                .iter()
                .enumerate()
                .map(|(index, (key, text))| {
                    let one = |texts: &[String]| match texts.get(index) {
                        Some(raw) => {
                            let c = compare(text, raw);
                            serde_json::json!({ "exact": c.exact, "class": c.class, "distance": c.distance, "got": c.got })
                        }
                        None => serde_json::Value::Null,
                    };
                    serde_json::json!({ "input": key, "pdfium": one(&o.pdfium_text), "pdfkit": one(&o.pdfkit_text) })
                })
                .collect();
            serde_json::json!({
                "variant": o.spec_key,
                "font": o.font_key,
                "qpdf_check": o.qpdf,
                "file_bytes": o.inspection.file_size,
                "font_program_bytes": o.inspection.font_programs,
                "original_ttf_bytes": o.font_file_size,
                "cid_to_gid_map": o.inspection.cid_to_gid,
                "font_subtypes": o.inspection.font_subtypes,
                "has_to_unicode": o.inspection.has_to_unicode,
                "to_unicode_entries": o.inspection.to_unicode.len(),
                "used_glyphs": o.tounicode_used,
                "used_glyphs_mapped": o.tounicode_mapped,
                "used_glyphs_mapped_correctly": o.tounicode_correct,
                "route_a_objects_per_page": o.a_stats.as_ref().map(|s| s.objects.clone()),
                "pages": o.inspection.pages.iter().map(|p| serde_json::json!({
                    "content_bytes": p.content_bytes, "show_ops": p.show_ops,
                    "text_objects": p.text_objects, "marked_spans": p.marked_spans,
                })).collect::<Vec<_>>(),
                "render_pixels_differing_from_b_src": o.render_diff,
                "extraction": extraction,
            })
        })
        .collect();
    let insertion_json: Vec<serde_json::Value> = insertions
        .iter()
        .map(|o| {
            serde_json::json!({
                "source": o.case, "route": o.route, "file": format!("{}.pdf", o.stem),
                "source_bytes": o.source_bytes,
                "output_bytes": o.result.as_ref().ok(),
                "error": o.result.as_ref().err(),
                "millis": o.millis, "qpdf_check": o.qpdf, "text_objects_added": o.objects,
                "content_streams_on_page": o.content_streams,
                "content_bytes_kept": o.content_kept,
                "pixels_changed_above_line": o.pixels_changed,
                "pixels_changed_in_band": o.band_pixels_changed,
                "pdfium_text_kept": o.pdfium_text_kept.map(|k| k.label()),
                "pdfkit_text_kept": o.pdfkit_text_kept.map(|k| k.label()),
                "output_encrypted": o.output_encrypted,
                "object_definitions_in_output": o.objects_written,
                "object_definitions_after_source_copy": o.objects_after_source,
                "pdfium_opens_source": o.pdfium_opens_source,
                "pdfium_opens_output": o.pdfium_opens_output,
            })
        })
        .collect();
    let json = serde_json::json!({ "outputs": json, "insertions": insertion_json });
    std::fs::write(out_dir.join("results.json"), serde_json::to_string_pretty(&json)?)?;
    Ok(())
}
